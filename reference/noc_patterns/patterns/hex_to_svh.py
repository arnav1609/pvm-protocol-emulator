"""hex_to_svh.py -- turn a $readmemh word image (one @0 address, then one 32-bit word per line) into a read-only
SystemVerilog include, so a bench can preload IMEM without a run-directory-relative file path (the dual-lane harness
runs XSim inside a generated workspace where `sw/...` does not exist). Lane 1, 2026-11-07.

Usage: python -I scripts/hex_to_svh.py <in.hex> <out.svh> <NAME>
"""
import hashlib, sys
from pathlib import Path

src, dst, name = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
words = []
for raw in src.read_text().split():
    if raw.startswith('@'):
        if int(raw[1:], 16) != len(words): raise SystemExit(f'non-contiguous address {raw}')
        continue
    if len(raw) != 8: raise SystemExit(f'not a 32-bit word: {raw}')
    words.append(raw.upper())
if not words: raise SystemExit('empty image')
digest = hashlib.sha256(src.read_bytes()).hexdigest()
lines = [f'// GENERATED by scripts/hex_to_svh.py from {src.as_posix()} (sha256 {digest}); do not edit.',
         f'localparam int {name}_N = {len(words)};',
         f'localparam logic [31:0] {name} [0:{len(words) - 1}] = \'{{']
lines += ['    ' + ', '.join(f"32'h{w}" for w in words[i:i + 8]) + (',' if i + 8 < len(words) else '') for i in range(0, len(words), 8)]
lines += ['};']
dst.parent.mkdir(parents=True, exist_ok=True)
dst.write_text('\n'.join(lines) + '\n', newline='\n')
print(f'{name}: {len(words)} words -> {dst.as_posix()}')
